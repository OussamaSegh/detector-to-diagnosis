"""The book's palette (book/tools/palette.json) for each color profile.

    python3 book/tools/palette.py tex <screen|boox|bw> OUT.tex   LaTeX color definitions
    python3 book/tools/palette.py css OUT.css                     EPUB colors (screen profile)
    python3 book/tools/palette.py check                          contrast and gray checks

A profile is the medium: screen (the PDF and the EPUB), boox (a color E Ink tablet: stronger
tints) and bw (a black ink paperback: every color replaced by the gray of the same lightness).
The figures read the same file through book/figures/lib/d2d.py.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PALETTE = json.loads((HERE / "palette.json").read_text())


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _lin(c):
    c = c / 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(h):
    r, g, b = rgb(h)
    return 0.2126 * _lin(r) + 0.7152 * _lin(g) + 0.0722 * _lin(b)


def lstar(h):
    y = luminance(h)
    return 116 * y ** (1 / 3) - 16 if y > 0.008856 else 903.3 * y


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def gray(h):
    """The gray with the same relative luminance as h."""
    y = luminance(h)
    c = 12.92 * y if y <= 0.0031308 else 1.055 * y ** (1 / 2.4) - 0.055
    v = round(max(0.0, min(1.0, c)) * 255)
    return f"{v:02X}{v:02X}{v:02X}"


def colors(profile):
    """Every named color of a profile, as {name: hex}."""
    p = PALETTE["profiles"][profile]
    out = {f"d2d{k}": v for k, v in PALETTE["base"].items()}
    out.update({f"d2dpart{k}": v[1] for k, v in PALETTE["parts"].items()})
    out.update({f"d2d{k}": v for k, v in PALETTE["semantic"].items()})
    out.update({f"d2dcat{i}": v for i, v in enumerate(PALETTE["categorical"])})
    if p["gray"]:
        out = {k: gray(v) for k, v in out.items()}
    return out


def tex(profile, dst):
    p = PALETTE["profiles"][profile]
    lines = [f"% Generated by book/tools/palette.py from palette.json, profile {profile}. Do not edit."]
    for name, h in colors(profile).items():
        lines.append(f"\\definecolor{{{name}}}{{HTML}}{{{h}}}")
    lines += [
        f"\\def\\dtint{{{p['tint']}}}",
        f"\\def\\dstrongtint{{{p['strong_tint']}}}",
        f"\\def\\dminline{{{p['min_line_pt']}pt}}",
        f"\\def\\dprofile{{{profile}}}",
        # Names the older templates and the metadata use.
        "\\colorlet{nlfblue}{d2dteal}\\colorlet{nlfred}{d2dregulated}\\colorlet{nlfgreen}{d2dexercise}",
        "\\colorlet{nlfgold}{d2dmilestone}\\colorlet{nlfgrey}{d2dnote}",
        "\\colorlet{partcolor}{d2dpart0}",
    ]
    pathlib.Path(dst).write_text("\n".join(lines) + "\n")


def mix(h, amount):
    """h mixed with white: amount 0 is white, 1 is h."""
    return "".join(f"{round(255 - amount * (255 - c)):02X}" for c in rgb(h))


# EPUB call-outs: class -> semantic color (templates/epub.css has the layout).
BOXES = {"box-why": "why", "box-regulated": "regulated", "box-askteam": "askteam",
         "box-mistakes": "mistakes", "box-note": "note", "box-milestone": "milestone",
         "box-exercise": "exercise", "box-objectives": "objectives", "box-prereq": "objectives",
         "box-check": "check", "box-summary": "summary"}


def css(dst):
    """The colored rules of the EPUB stylesheet. Readers ignore CSS variables unevenly, so every
    rule is written out per Part (the chapter's section carries class part-N, from design.lua)."""
    lines = ["/* Generated by book/tools/palette.py from palette.json. Do not edit. */"]
    ink = PALETTE["base"]["ink"]
    sand = PALETTE["base"]["sand"]
    for k, (_, h) in PALETTE["parts"].items():
        part = f"section.part-{k}"
        # The part opener keeps a colored title. A chapter title is the text ink, with the
        # Part color on the kicker (data-kicker) and the rule. The why-card uses the same bar.
        lines += [
            f"h1.part.part-{k} {{ color: #{h}; border-bottom: none; }}",
            f"{part} > h1:not(.part) {{ color: #{ink}; border-bottom: 2px solid #{h}; }}",
            f"{part} > h1:not(.part)::before {{ content: attr(data-kicker); display: block; "
            f"font-family: Inter, \"Helvetica Neue\", Arial, sans-serif; font-size: 0.36em; "
            f"font-weight: 600; letter-spacing: 0.14em; text-transform: uppercase; "
            f"color: #{h}; margin-bottom: 0.4em; }}",
            f"{part} h2 {{ color: #{h}; border-bottom-color: #{mix(h, 0.35)}; }}",
            f"{part} h2.opener-head {{ color: #{h}; border-bottom: none; }}",
            f"{part} div.box-why {{ background: #{sand}; border-color: transparent; border-left: 4px solid #{h}; }}",
            f"{part} div.box-why div.box-title p {{ color: #{ink}; }}",
            f"{part} h3, {part} h4 {{ color: #{h}; }}",
            f"{part} th {{ background: #{mix(h, 0.12)}; }}",
            f"{part} pre {{ border-left: 3px solid #{h}; }}",
            f"{part} figcaption strong, {part} div.listing-caption strong {{ color: #{h}; }}",
        ]
    for cls, sem in BOXES.items():
        h = PALETTE["semantic"][sem]
        lines += [f"div.{cls} {{ border-color: #{mix(h, 0.5)}; border-left: 5px solid #{h}; background: #{mix(h, 0.06)}; }}",
                  f"div.{cls} div.box-title p {{ color: #{h}; }}"]
    pathlib.Path(dst).write_text("\n".join(lines) + "\n")


def check():
    """White text on every Part and callout color, and colored text on paper, at least 4.5:1."""
    bad = []
    for name, h in colors("screen").items():
        if name.startswith(("d2dpart", "d2dwhy", "d2dregulated", "d2dmistakes", "d2dexercise",
                            "d2daskteam", "d2dmilestone", "d2dnote", "d2dcheck", "d2dsummary",
                            "d2dobjectives", "d2dteal", "d2dviolet", "d2dcyan", "d2dgold")):
            c = contrast(h, "FFFFFF")
            if c < 4.5:
                bad.append(f"{name} #{h}: {c:.2f}:1 against white, needs 4.5:1")
    for b in bad:
        print("palette:", b)
    print(f"palette: {len(colors('screen'))} colors, {len(bad)} problems")
    return 1 if bad else 0


if __name__ == "__main__":
    if sys.argv[1:2] == ["tex"]:
        tex(sys.argv[2], sys.argv[3])
    elif sys.argv[1:2] == ["css"]:
        css(sys.argv[2])
    elif sys.argv[1:2] == ["check"]:
        sys.exit(check())
    else:
        sys.exit(__doc__)
