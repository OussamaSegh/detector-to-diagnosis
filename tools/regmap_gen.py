"""Generates a C++ register map and its documentation from a TOML specification (Chapter 22).

The specification (hw/feb.toml) is the single source of a device's registers. This tool checks
it (aligned, distinct addresses; fields inside 32 bits that do not overlap; reset values that fit)
and writes:
  - a C++ header of types for minidaq/hw/register.hpp: a struct per register, a struct per field;
  - a Markdown table for people.
TOML, not YAML: Python reads TOML with its standard library (tomllib), so the tool adds no
package to MiniDAQ's tool list.

Usage: regmap_gen.py SPEC --header OUT.hpp --doc OUT.md [--check]
--check compares instead of writing and fails if a file is out of date. Exit status 0: ok,
1: out of date, 2: the specification is invalid.
"""
import argparse
import pathlib
import sys
import tomllib

ACCESS = ("ro", "rw", "wo", "rw1c")


class SpecError(Exception):
    pass


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def load(text: str) -> dict:
    try:
        spec = tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise SpecError(f"not valid TOML: {e}") from e
    check(spec)
    return spec


def check(spec: dict) -> None:
    m = spec.get("map")
    if not isinstance(m, dict) or not str(m.get("name", "")).isidentifier():
        raise SpecError("[map] needs a name that is a C++ identifier")
    if m.get("width", 32) != 32:
        raise SpecError("only 32-bit registers are supported")
    regs = spec.get("register", [])
    if not regs:
        raise SpecError("no [[register]]")
    seen_addr, seen_name = {}, set()
    for r in regs:
        name = r.get("name", "")
        where = f"register '{name}'"
        if not name.isidentifier() or name in seen_name:
            raise SpecError(f"{where}: a name must be a unique identifier")
        seen_name.add(name)
        addr = r.get("address")
        if not isinstance(addr, int) or addr < 0 or addr % 4 != 0:
            raise SpecError(f"{where}: the address must be a multiple of 4")
        if addr in seen_addr:
            raise SpecError(f"{where}: address 0x{addr:03X} is also {seen_addr[addr]}")
        seen_addr[addr] = name
        if r.get("access") not in ACCESS:
            raise SpecError(f"{where}: access must be one of {', '.join(ACCESS)}")
        reset = r.get("reset", 0)
        if not isinstance(reset, int) or not 0 <= reset <= 0xFFFFFFFF:
            raise SpecError(f"{where}: the reset value must fit 32 bits")
        used = 0
        fnames = set()
        for f in r.get("fields", []):
            fw = f"{where}, field '{f.get('name', '')}'"
            if not str(f.get("name", "")).isidentifier() or f["name"] in fnames:
                raise SpecError(f"{fw}: a name must be a unique identifier")
            fnames.add(f["name"])
            lsb, width = f.get("lsb"), f.get("width")
            if not isinstance(lsb, int) or not isinstance(width, int) or lsb < 0 or width < 1 or lsb + width > 32:
                raise SpecError(f"{fw}: bits {lsb}..{lsb}+{width} are not inside 32 bits")
            bits = ((1 << width) - 1) << lsb
            if used & bits:
                raise SpecError(f"{fw}: overlaps another field")
            used |= bits
        if reset & ~used & 0xFFFFFFFF:
            raise SpecError(f"{where}: the reset value sets bits outside every field")


def header(spec: dict, source: str) -> str:
    m = spec["map"]
    ns = m["name"]
    out = [
        "// SPDX-License-Identifier: MIT",
        f"// Generated by tools/regmap_gen.py from {source}. Do not edit: change the specification",
        "// and run the generator (the test docs.regmap fails while this file is out of date).",
        f"// {m.get('title', ns)}, register map version {m.get('version', '')}.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        '#include "minidaq/hw/register.hpp"',
        "",
        f"namespace minidaq::hw::{ns} {{",
        "",
        f'inline constexpr std::string_view map_version = "{m.get("version", "")}";',
        "",
    ]
    for r in spec["register"]:
        out.append(f"// {r.get('description', '')}")
        out.append(
            f"struct {camel(r['name'])} : Register<0x{r['address']:03X}, Access::{r['access']}, "
            f"0x{r.get('reset', 0):08X}> {{"
        )
        for f in r.get("fields", []):
            signed = ", true" if f.get("signed") else ""
            unit = f" [{f['unit']}]" if f.get("unit") else ""
            out.append(f"  // {f.get('description', '')}{unit}")
            out.append(f"  struct {camel(f['name'])} : Field<{camel(r['name'])}, {f['lsb']}, {f['width']}{signed}> {{}};")
        out.append("};")
        out.append("")
    out.append(f"inline constexpr std::array<RegisterInfo, {len(spec['register'])}> registers{{{{")
    for r in spec["register"]:
        out.append(
            f'    {{"{r["name"]}", {camel(r["name"])}::address, {camel(r["name"])}::access, '
            f'{camel(r["name"])}::reset}},'
        )
    out.append("}};")
    out.append("")
    out.append(f"}}  // namespace minidaq::hw::{ns}")
    return "\n".join(out) + "\n"


def doc(spec: dict, source: str) -> str:
    m = spec["map"]
    out = [
        f"# {m.get('title', m['name'])}: register map",
        "",
        f"Version {m.get('version', '')}. Generated by `tools/regmap_gen.py` from `{source}`; do not edit.",
        "Registers are 32 bits wide. Access: ro read only, rw read and write, wo write only,",
        "rw1c read, and writing 1 to a bit clears it.",
        "",
        "| Address | Register | Access | Reset | Field | Bits | Description |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in spec["register"]:
        first = True
        for f in r.get("fields", []):
            hi = f["lsb"] + f["width"] - 1
            bits = f"{hi}:{f['lsb']}" if f["width"] > 1 else f"{f['lsb']}"
            unit = f" ({f['unit']})" if f.get("unit") else ""
            signed = ", signed" if f.get("signed") else ""
            desc = f"{f.get('description', '')}{unit}{signed}".strip().replace("|", "\\|")
            if first:
                out.append(
                    f"| `0x{r['address']:03X}` | `{r['name']}` | {r['access']} | `0x{r.get('reset', 0):08X}` "
                    f"| `{f['name']}` | {bits} | {desc} |"
                )
                first = False
            else:
                out.append(f"| | | | | `{f['name']}` | {bits} | {desc} |")
    out.append("")
    for r in spec["register"]:
        out.append(f"- `{r['name']}`: {r.get('description', '')}")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("spec", type=pathlib.Path)
    ap.add_argument("--header", type=pathlib.Path, required=True)
    ap.add_argument("--doc", type=pathlib.Path, required=True)
    ap.add_argument("--source-name", help="the specification's path as written in the outputs")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        spec = load(a.spec.read_text())
    except SpecError as e:
        print(f"{a.spec}: {e}", file=sys.stderr)
        return 2
    source = a.source_name or a.spec.as_posix()
    wanted = {a.header: header(spec, source), a.doc: doc(spec, source)}
    stale = []
    for path, text in wanted.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        for p in stale:
            print(f"{p} is out of date: run tools/regmap_gen.py", file=sys.stderr)
        return 1
    print(f"regmap: {len(spec['register'])} registers of '{spec['map']['name']}', "
          + ("up to date" if a.check else "written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
