"""Runs MiniDAQ's system tests and writes the software system test report (Chapter 19).

The system test plan (docs/regulatory/verification/stp.md) says what is tested, how and with
what pass criteria. This tool produces the record of one execution of that plan: for the
commit and the build given, every system test case with its requirements, its result and its
duration, the environment, the deviations, and a place for the reviewer's signature. A report
that a person types from memory is not evidence; this one is made by the run it reports.

    tools/test_report.py BUILD OUT.md [--tester NAME]

BUILD is a configured and built CMake build directory (its programs are in BUILD/minidaq/apps).
Exits with 1 if a test case failed or errored, so a release cannot cite a failing report.
"""
import argparse
import datetime
import importlib
import inspect
import io
import os
import pathlib
import platform
import re
import subprocess
import sys
import time
import unittest

ROOT = pathlib.Path(__file__).resolve().parent.parent
SYSTEM = ROOT / "minidaq/tests/system"
MODULES = ["test_control_system", "test_acquisition_system", "test_readout_system", "test_stats"]
TAG = re.compile(r"#\s*REQ:\s*(SRS-[A-Z]+-\d{3}(?:\s*,\s*SRS-[A-Z]+-\d{3})*)")


def requirements_of(test):
    """The requirement IDs in the REQ comment of a test method."""
    method = getattr(test, test._testMethodName)
    m = TAG.search(inspect.getsource(method))
    return [r.strip() for r in m.group(1).split(",")] if m else []


class Recorder(unittest.TextTestResult):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.rows = []
        self._start = 0.0

    def startTest(self, test):
        self._start = time.monotonic()
        super().startTest(test)

    def _row(self, test, outcome, detail=""):
        self.rows.append((test, outcome, time.monotonic() - self._start, detail))

    def addSuccess(self, test):
        super().addSuccess(test)
        self._row(test, "pass")

    def addFailure(self, test, err):
        super().addFailure(test, err)
        self._row(test, "FAIL", self._exc_info_to_string(err, test).strip().splitlines()[-1])

    def addError(self, test, err):
        super().addError(test, err)
        self._row(test, "ERROR", self._exc_info_to_string(err, test).strip().splitlines()[-1])

    def addSkip(self, test, reason):
        super().addSkip(test, reason)
        self._row(test, "skipped", reason)


def git(*args):
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True).stdout.strip()


def cache_value(build, key):
    cache = (build / "CMakeCache.txt").read_text()
    m = re.search(rf"^{key}:[A-Z]+=(.*)$", cache, re.M)
    return m.group(1) if m else "?"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("build", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    ap.add_argument("--tester", default=os.environ.get("USER", "unknown"))
    args = ap.parse_args()
    build = args.build.resolve()
    os.environ["MINIDAQ_APPS"] = str(build / "minidaq/apps")
    sys.path.insert(0, str(SYSTEM))

    suite = unittest.TestSuite()
    for name in MODULES:
        suite.addTests(unittest.defaultTestLoader.loadTestsFromModule(importlib.import_module(name)))
    started = datetime.datetime.now(datetime.timezone.utc)
    log = io.StringIO()
    result = unittest.TextTestRunner(stream=log, resultclass=Recorder, verbosity=2).run(suite)

    commit = git("rev-parse", "--short=12", "HEAD")
    dirty = bool(git("status", "--porcelain", "--untracked-files=no"))
    failed = [r for r in result.rows if r[1] in ("FAIL", "ERROR")]
    lines = [
        "# MiniDAQ software system test report",
        "",
        "Generated by `tools/test_report.py`; the execution of the system test plan",
        "(`docs/regulatory/verification/stp.md`) that this report records.",
        "",
        "## 1. Identification",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Software | MiniDAQ {(ROOT / 'VERSION').read_text().strip()}, commit `{commit}`"
        f"{' with uncommitted changes (not valid as evidence)' if dirty else ''} |",
        f"| Build | `{build.name}`: {cache_value(build, 'CMAKE_BUILD_TYPE') or 'no build type'}, "
        f"`{pathlib.Path(cache_value(build, 'CMAKE_CXX_COMPILER')).name}`, sanitizers "
        f"`{cache_value(build, 'MINIDAQ_SANITIZERS') or 'none'}` |",
        f"| Machine | {platform.node()}, {platform.system()} {platform.release()}, {os.cpu_count()} CPUs, "
        f"Python {platform.python_version()} |",
        f"| Executed | {started:%Y-%m-%d %H:%M} UTC by {args.tester} |",
        "",
        "## 2. Results",
        "",
        f"{result.testsRun} test cases: {sum(r[1] == 'pass' for r in result.rows)} passed, "
        f"{len(failed)} failed, {sum(r[1] == 'skipped' for r in result.rows)} skipped.",
        "",
        "| Test case | Requirements | Result | Time, s |",
        "|---|---|---|---|",
    ]
    for test, outcome, seconds, _ in result.rows:
        module, cls, method = test.id().split(".")
        reqs = ", ".join(requirements_of(test)) or "(test tool)"
        lines.append(f"| `{module}.py` {cls}.{method} | {reqs} | {outcome} | {seconds:.1f} |")
    lines += ["", "## 3. Deviations and anomalies", ""]
    if failed or dirty:
        for test, outcome, _, detail in failed:
            lines.append(f"- {test.id()}: {outcome}: {detail}")
        if dirty:
            lines.append("- The working tree had uncommitted changes: repeat on a clean commit.")
    else:
        lines.append("None: every test case passed on a clean commit. Open problem reports are listed in")
        lines.append("`docs/regulatory/known-anomalies.md` for the release.")
    lines += [
        "",
        "## 4. Conclusion and review",
        "",
        "The system tests " + ("passed." if not failed else "did NOT pass."),
        "",
        "| Role | Name | Date | Signature |",
        "|---|---|---|---|",
        f"| Tester | {args.tester} | {started:%Y-%m-%d} | |",
        "| Reviewer | | | |",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    (args.out.with_suffix(".log")).write_text(log.getvalue())
    print(f"{args.out}: {result.testsRun} test cases, {len(failed)} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
