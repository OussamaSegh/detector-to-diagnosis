"""MiniDAQ's design and development file index and document control (Chapter 16).

docs/regulatory/qms/design-file.json maps the design and development clauses of ISO 13485
(7.3.2 to 7.3.10) and the related QMS clauses to the documents and records that are their
evidence, and lists which documents are controlled. This tool:

1. checks that every evidence path is tracked by git (a file, or a directory ending in "/" that
   holds one), that every 7.3 subclause has evidence or states the plan for it, and that every
   file under docs/ is indexed, so that nothing in the design file is an orphan;
2. checks document control: a controlled document states "Version N" in its first lines and
   ends its history table with version N, numbered 1, 2, 3 ... without gaps;
3. with --since REF, fails for every controlled document that changed since the git ref REF
   (normally the last release tag) and still has the version it had there;
4. with --write, generates docs/regulatory/qms/design-file.md from the index.

Usage: design_file.py ROOT [--write | --check] [--since REF]. Exit status 0 if all holds.
"""
import json
import pathlib
import re
import subprocess
import sys

INDEX = pathlib.Path("docs/regulatory/qms/design-file.json")
OUT = pathlib.Path("docs/regulatory/qms/design-file.md")
DESIGN = ("7.3.2", "7.3.3", "7.3.4", "7.3.5", "7.3.6", "7.3.7", "7.3.8", "7.3.9", "7.3.10")
VERSION = re.compile(r"^Version (\d+)\b", re.M)
HISTORY_HEADING = re.compile(r"^## (?:\d+\. )?(?:Changes|Document history)\b.*$", re.M)
HISTORY_ROW = re.compile(r"^\|\s*(\d+)\s*\|", re.M)


def tracked(root, sub):
    out = subprocess.run(["git", "-C", str(root), "ls-files", sub], capture_output=True, text=True, check=True)
    return [line for line in out.stdout.splitlines() if line]


def covered(path, evidence):
    return any(path == e or (e.endswith("/") and path.startswith(e)) for e in evidence)


# [snippet:version]
def version_of(text):
    """The document's version, and the problems of its history table."""
    head = "\n".join(text.splitlines()[:6])
    m = VERSION.search(head)
    if not m:
        return None, ["no 'Version N' line at the top"]
    version = int(m.group(1))
    h = HISTORY_HEADING.search(text)
    if not h:
        return version, ["no history table ('## Changes' or '## Document history')"]
    table = text[h.end():].split("\n## ", 1)[0]
    rows = [int(n) for n in HISTORY_ROW.findall(table)]
    problems = []
    if rows != list(range(1, len(rows) + 1)):
        problems.append(f"history versions {rows} are not 1, 2, 3, ...")
    if not rows or rows[-1] != version:
        problems.append(f"version {version} at the top, {rows[-1] if rows else 'none'} last in the history")
    return version, problems
# [/snippet:version]


def check_index(root, index):
    errors = []
    evidence = []
    seen = set()
    files = tracked(root, ".")
    for c in index["clauses"]:
        seen.add(c["clause"])
        for e in c["evidence"]:
            evidence.append(e)
            # A record exists only once it is in git: an empty or untracked directory is not one.
            if not any(covered(f, [e]) for f in files):
                errors.append(f"{c['clause']}: evidence {e} is not in the repository")
        if not c["evidence"] and not c.get("plan"):
            errors.append(f"{c['clause']}: no evidence and no plan")
    for d in DESIGN:
        if d not in seen:
            errors.append(f"clause {d} is not in the index")
    for f in tracked(root, "docs"):
        if not covered(f, evidence):
            errors.append(f"{f} is in no clause of the design file")
    return errors


def check_controlled(root, index, since=None):
    errors = []
    for doc in index["controlled"]:
        p = root / doc
        if not p.is_file():
            errors.append(f"{doc}: controlled document does not exist")
            continue
        text = p.read_text()
        version, problems = version_of(text)
        errors += [f"{doc}: {m}" for m in problems]
        if since and version is not None:
            # [snippet:since]
            old = subprocess.run(["git", "-C", str(root), "show", f"{since}:{doc}"], capture_output=True, text=True)
            if old.returncode == 0 and old.stdout != text and version_of(old.stdout)[0] == version:
                errors.append(f"{doc}: changed since {since} but still version {version}")
            # [/snippet:since]
    return errors


def render(index):
    lines = ["# MiniDAQ design and development file", "",
             "Generated by `tools/design_file.py --write` from `design-file.json`. Do not edit by hand:",
             "the test `docs.design_file` fails when this file is out of date.", "",
             index["intro"], "",
             "| Clause | Topic | Evidence | Notes |", "|---|---|---|---|"]
    for c in index["clauses"]:
        ev = "<br>".join(f"`{e}`" for e in c["evidence"]) or "none yet"
        note = c.get("plan") or c.get("note", "")
        lines.append(f"| {c['clause']} | {c['topic']} | {ev} | {note} |")
    lines += ["", "## Controlled documents", "",
              "Each states its version at the top and its history at the end; `docs.design_file` checks",
              "both, and CI checks that a document changed since the last release has a new version.", ""]
    lines += [f"- `{d}`" for d in index["controlled"]]
    return "\n".join(lines) + "\n"


def main(argv):
    root = pathlib.Path(argv[1]).resolve()
    args = argv[2:]
    since = args[args.index("--since") + 1] if "--since" in args else None
    index = json.loads((root / INDEX).read_text())
    errors = check_index(root, index) + check_controlled(root, index, since)
    text = render(index)
    if "--write" in args:
        (root / OUT).write_text(text)
    elif "--check" in args and ((root / OUT).read_text() if (root / OUT).exists() else "") != text:
        errors.append(f"{OUT} is out of date: run tools/design_file.py . --write")
    for e in errors:
        print(e)
    print(f"design file: {len(index['clauses'])} clauses, {len(index['controlled'])} controlled documents, "
          + ("ok" if not errors else f"{len(errors)} problem(s)"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
